-- Despesas operacionais da loja (aluguel, energia, salários etc.)
-- Rodar UMA vez no Supabase: painel do projeto → SQL Editor → New query → colar → Run.
-- É só um acréscimo: não altera nem apaga nenhuma tabela existente.
-- Para desfazer: drop table public.custos_operacionais;

create table if not exists public.custos_operacionais (
  id bigint generated by default as identity primary key,
  competencia text not null check (competencia ~ '^\d{4}-\d{2}$'),  -- mês do custo, ex.: 2026-10
  categoria text not null,                                           -- ex.: Aluguel, Energia, Salários
  descricao text not null default '',
  valor numeric(12,2) not null check (valor >= 0),
  data_pagamento date,
  created_at timestamptz not null default now()
);

create index if not exists custos_operacionais_competencia_idx on public.custos_operacionais (competencia);

-- Mesmo acesso das outras tabelas do sistema hoje (o sistema ainda não tem login).
-- Quando o login for implantado, estas regras serão restringidas junto com as demais tabelas.
alter table public.custos_operacionais enable row level security;
drop policy if exists "sistema_acesso_total" on public.custos_operacionais;
create policy "sistema_acesso_total" on public.custos_operacionais
  for all to anon, authenticated using (true) with check (true);
